// Report helper for scripts/deps-weekly.sh.
//
// Reads two taze --json dumps: one in `minor` mode (the updates the automatic
// run writes) and one in `major` mode (everything, including the majors that
// stay for a human). Prints either a terminal summary or the pull request body.
//
// Usage:
//   node scripts/deps-weekly-report.mjs summary <auto.json> <all.json>
//   node scripts/deps-weekly-report.mjs markdown <auto.json> <all.json> [out.md] [base] [gates]

import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'

const KINDS = ['patch', 'minor', 'major']

function fail(message) {
  console.error(message)
  process.exit(2)
}

const [kind, autoPath, allPath, outPath, base, gates] = process.argv.slice(2)
if (!kind || !autoPath || !allPath)
  fail('usage: node scripts/deps-weekly-report.mjs <summary|markdown> <auto.json> <all.json> [out.md]')

function readDeps(path) {
  const data = JSON.parse(readFileSync(path, 'utf8'))
  return (data.packages ?? [])
    .flatMap(pkg => pkg.resolved ?? [])
    .filter(dep => dep.update && dep.name && dep.currentVersion && dep.targetVersion)
}

const auto = dedupe(readDeps(autoPath)).sort(compareByName)
const all = dedupe(readDeps(allPath))
const autoNames = new Set(auto.map(dep => dep.name))
const manual = all.filter(dep => !autoNames.has(dep.name)).sort(compareByName)

// GitHub Actions entries repeat once per workflow job, keep one row per target.
function dedupe(list) {
  const seen = new Map()
  for (const dep of list) {
    const key = `${dep.name}@${dep.currentVersion}->${dep.targetVersion}`
    const hit = seen.get(key)
    if (hit)
      hit.count += 1
    else
      seen.set(key, { ...dep, count: 1 })
  }
  return [...seen.values()]
}

function label(dep) {
  return dep.count > 1 ? `${dep.name} ×${dep.count}` : dep.name
}

function compareByName(a, b) {
  return a.name.localeCompare(b.name)
}

function countByDiff(list) {
  const counts = { patch: 0, minor: 0, major: 0, other: 0 }
  for (const dep of list) {
    if (KINDS.includes(dep.diff))
      counts[dep.diff] += 1
    else
      counts.other += 1
  }
  return counts
}

function pad(text, width) {
  const value = String(text)
  return value.length >= width ? value : value + ' '.repeat(width - value.length)
}

function summary() {
  const autoCounts = countByDiff(auto)
  console.log(`\n    automatic: ${auto.length} to write (patch ${autoCounts.patch}, minor ${autoCounts.minor})`)
  for (const dep of auto)
    console.log(`      ${pad(label(dep), 32)} ${pad(dep.currentVersion, 11)} -> ${pad(dep.targetVersion, 11)} ${dep.diff}`)

  const manualCounts = countByDiff(manual)
  console.log(`\n    for a human: ${manual.length} left alone (major ${manualCounts.major}, other ${manualCounts.other})`)
  for (const dep of manual)
    console.log(`      ${pad(label(dep), 32)} ${pad(dep.currentVersion, 11)} -> ${pad(dep.targetVersion, 11)} ${dep.diff}`)
}

function table(list) {
  if (list.length === 0)
    return '_Nothing pending._\n'

  const head = '| dependency | before | after | bump |\n| --- | --- | --- | --- |\n'
  const rows = list
    .map(dep => `| \`${label(dep)}\` | \`${dep.currentVersion}\` | \`${dep.targetVersion}\` | ${dep.diff} |`)
    .join('\n')
  return `${head}${rows}\n`
}

function markdown() {
  const autoCounts = countByDiff(auto)
  const manualCounts = countByDiff(manual)
  const maturity = process.env.MATURITY_DAYS ?? '0'
  const gateList = (gates ?? '').split(' ').filter(Boolean)

  const body = `## Automatic part

Patch and minor bumps: ${auto.length} in total (patch ${autoCounts.patch}, minor ${autoCounts.minor}).
Releases younger than ${maturity} days were skipped, and \`${process.env.EXCLUDE ?? 'none'}\` was left out on purpose.

${table(auto)}
## Left for a human

${manual.length} dependencies stay out of this pull request (major ${manualCounts.major}, other ${manualCounts.other}).
Major bumps are a separate decision, and \`pnpm\` must be bumped together with the
\`version:\` pin of \`pnpm/action-setup\` in \`.github/workflows/*.yml\`.

${table(manual)}
## Checks

${gateList.length > 0 ? gateList.map(gate => `- \`pnpm ${gate}\`: pass`).join('\n') : '- not recorded'}

Generated by \`scripts/deps-weekly.sh\` (base \`${base ?? 'main'}\`). The full log stays on the machine that ran it.
`

  if (outPath)
    writeFileSync(outPath, body)
  else
    process.stdout.write(body)
}

if (kind === 'summary')
  summary()
else if (kind === 'markdown')
  markdown()
else
  fail(`unknown kind: ${kind}`)
